/**
 * One-off helper: parse [data-preset="..."] blocks → templates/definitions/builtin/themes.generated.js
 * Run: node scripts/extract-preset-themes.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const cssFiles = [
  path.join(root, 'index.css'),
  path.join(root, 'presets-v21-v40.css'),
];

const VAR_MAP = {
  '--cv-font-title': 'fontTitle',
  '--cv-font-body': 'fontBody',
  '--cv-bg': 'bg',
  '--cv-sidebar-bg': 'sidebarBg',
  '--cv-primary': 'primary',
  '--cv-secondary': 'secondary',
  '--cv-accent': 'accent',
  '--cv-text': 'text',
  '--cv-text-light': 'textLight',
  '--cv-border': 'border',
  '--cv-sidebar-width': 'sidebarWidth',
  '--cv-header-bg': 'headerBg',
  '--cv-header-color': 'headerColor',
  '--cv-sidebar-primary': 'sidebarPrimary',
};

const blockRe = /\[data-preset="([^"]+)"\]\s*\{([^}]+)\}/g;
const themes = {};

for (const file of cssFiles) {
  const css = fs.readFileSync(file, 'utf8');
  let m;
  while ((m = blockRe.exec(css)) !== null) {
    const id = m[1];
    const body = m[2];
    if (!themes[id]) themes[id] = {};
    for (const [cssKey, jsKey] of Object.entries(VAR_MAP)) {
      const propRe = new RegExp(`${cssKey.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*:\\s*([^;]+);`);
      const pm = body.match(propRe);
      if (pm) themes[id][jsKey] = pm[1].trim();
    }
  }
}

const outPath = path.join(root, 'src', 'templates', 'definitions', 'builtin', 'themes.generated.js');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
const body = `/** Auto-generated by scripts/extract-preset-themes.mjs — do not hand-edit */\nexport const BUILTIN_THEMES = ${JSON.stringify(themes, null, 2)};\n`;
fs.writeFileSync(outPath, body, 'utf8');
console.log(`Wrote ${Object.keys(themes).length} themes → ${outPath}`);
